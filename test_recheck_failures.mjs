import assert from 'node:assert/strict';
import {currentFailedDetailURLs,applyFailedRechecks} from './supabase/functions/registry-discovery/recheck-failures.mjs';
const stamp='2026-10-26T15:08:15.226227+00:00';
const source={id:51,url:'https://www.propertymarket.com.mt/'};
const validURL=(url,root)=>{if(new URL(url).origin!==new URL(root).origin)throw Error('Cross-source URL');return url};
const fail=(checked_at,url=source.url+'view/123/',mode='detail')=>({checked_at,url,mode});
const historical=Array.from({length:221},(_,i)=>fail('2026-10-25T12:00:00Z',source.url+'view/'+i));
const state={checked_at:stamp,failed_urls:historical};
const queries=[];const sql=async(parts,...args)=>{queries.push({query:parts.join('?'),args});return []};
await applyFailedRechecks(sql,source,state,validURL);
assert.equal(queries.length,0,'221 historical failures must cause no repeated updates');
state.failed_urls.push(fail(stamp),fail(stamp,source.url+'view/123'),fail(stamp,source.url+'index','index'));
assert.deepEqual(currentFailedDetailURLs(state,source.url,validURL),[source.url+'view/123']);
await applyFailedRechecks(sql,source,state,validURL);
assert.equal(queries.length,1,'all current detail failures use one update');
assert(queries[0].query.includes("l.state not in ('expired','removed')"),'failed rechecks preserve confirmed closures');
assert(queries[0].query.includes('c.source_id='),'cannot mark another source');
assert(queries[0].args.includes('registry-51'));
assert.deepEqual(queries[0].args.find(Array.isArray),[source.url+'view/123']);
queries.length=0;
await applyFailedRechecks(sql,source,{...state,error:'TimeoutError'},validURL);
assert.equal(queries.length,2,'source failure still marks outdated open records unknown');
assert(queries.every(q=>q.query.includes("l.state not in ('expired','removed')")));
assert.throws(()=>currentFailedDetailURLs({...state,failed_urls:[fail(stamp,'https://other.example/1')]},source.url,validURL),/Cross-source/);
assert.deepEqual(currentFailedDetailURLs({checked_at:stamp,failed_urls:[fail('invalid'),fail('2026-10-27T12:00:00Z')]},source.url,validURL),[]);
await assert.rejects(applyFailedRechecks(async()=>{throw Error('Database failure')},source,state,validURL),/Database failure/);
console.log('Historical failures are not replayed; new failures are batched; source identity, closures and database errors are preserved.');
